"""Player-declared NTRP level: catalog, copy, and coaching prompt."""

from __future__ import annotations

import re
from dataclasses import dataclass

DEFAULT_LEVEL = "3.0"


@dataclass(frozen=True)
class LevelInfo:
    code: str
    ntrp: float
    title: str
    blurb: str
    band: str

    @property
    def label(self) -> str:
        return f"{self.code} {self.title}"

    def as_public(self) -> dict:
        return {
            "code": self.code,
            "ntrp": self.ntrp,
            "title": self.title,
            "blurb": self.blurb,
            "band": self.band,
            "label": self.label,
        }


LEVELS: tuple[LevelInfo, ...] = (
    LevelInfo("2.0", 2.0, "入门", "刚能打到球，动作还在学", "beginner"),
    LevelInfo("2.5", 2.5, "初级", "能慢慢对打几拍，动作还不稳定", "beginner"),
    LevelInfo("3.0", 3.0, "进阶初级", "能稳定对拉，技术开始有框架", "developing"),
    LevelInfo("3.5", 3.5, "中级", "能变线，有一定旋转和脚步", "intermediate"),
    LevelInfo("4.0", 4.0, "中高级", "能主动进攻，动作比较完整", "advanced"),
    LevelInfo("4.5", 4.5, "高级", "能变化节奏和落点", "advanced"),
    LevelInfo("5.0", 5.0, "准专业", "接近竞技水平，技术完整", "elite"),
)

_BY_CODE = {item.code: item for item in LEVELS}


class _SafeMap(dict):
    def __missing__(self, key: str) -> str:
        return "{" + key + "}"


def parse_level(raw) -> LevelInfo:
    """Accept 3.5 / '3.5 中级' / 4. 未知或空则回落到 3.0。"""
    if raw is None or raw == "":
        return _BY_CODE[DEFAULT_LEVEL]
    if isinstance(raw, bool):
        return _BY_CODE[DEFAULT_LEVEL]
    if isinstance(raw, (int, float)):
        n = float(raw)
    else:
        text = str(raw).strip()
        if text in _BY_CODE:
            return _BY_CODE[text]
        match = re.search(r"(\d+(?:\.\d+)?)", text)
        if not match:
            return _BY_CODE[DEFAULT_LEVEL]
        n = float(match.group(1))
    n = min(5.0, max(2.0, n))
    code = f"{round(n * 2.0) / 2.0:.1f}"
    return _BY_CODE.get(code, _BY_CODE[DEFAULT_LEVEL])


def public_levels() -> list[dict]:
    return [item.as_public() for item in LEVELS]


def issue_text(issue: str, level: str | LevelInfo | None = None, **kwargs) -> tuple[str, str]:
    """Return (problem, drill) for this issue at this level. Drill may be empty."""
    info = level if isinstance(level, LevelInfo) else parse_level(level)
    table = _SCRIPTS.get(issue) or {}
    pair = table.get(info.code) or table.get(info.band) or table.get(DEFAULT_LEVEL)
    if not pair:
        return "", ""
    problem, drill = pair
    mapping = _SafeMap(kwargs)
    return problem.format_map(mapping), drill.format_map(mapping)


_BEGINNER_KEEP = (
    "偏晚",
    "击球点",
    "身前",
    "挤在",
    "贴在",
    "重心",
    "站得",
    "头肩",
    "引拍",
    "横",
    "转肩",
    "只动手",
)


def _rank_line(text: str) -> int:
    for i, key in enumerate(_BEGINNER_KEEP):
        if key in text:
            return i
    return 80


def trim_coaching(
    level: str | LevelInfo | None,
    strengths: list[str],
    problems: list[str],
    drills: list[str],
) -> tuple[list[str], list[str], list[str]]:
    """Beginners only need a few lines; keep 3.0+ close to the original volume."""
    info = level if isinstance(level, LevelInfo) else parse_level(level)
    if info.ntrp <= 2.5:
        problems = sorted(problems, key=_rank_line)[:3]
        drills = sorted(drills, key=_rank_line)[:2]
        return strengths[:2], problems, drills
    if info.ntrp >= 5.0:
        problems = [p for p in problems if "没有发现特别明显" not in p]
        return strengths[:4], problems[:5], drills[:3]
    return strengths, problems, drills


def prompt_level_block(level: str | LevelInfo | None = None) -> str:
    info = parse_level(level if not isinstance(level, LevelInfo) else level.code)
    card = _PROMPT_CARDS[info.code]
    return f"""【球员自评等级】{info.label}（NTRP）
{info.blurb}
这不是系统测出来的，是球员自己选的。解释、原因、口令和训练必须按这个等级写。
分数仍按这次动作的完成度给，不要因为等级低就故意打低分，也不要因为等级高就故意打高分。

{card}

【同一现象，必须按等级解释，禁止套同一句】
- 击球点偏晚：2.0–2.5 是人等球、引拍晚、在身体旁边捞；3.0–3.5 是转体没收完、步点不到、球挤到髋边；4.0–4.5 是对来球深度判断或还原偏慢、人被挤住；5.0 是高质量来球下的间距/提前量，禁止写「还不会打身前」。
- 重心偏高：2.0–2.5 是准备时腿是直的，先学会蹲一点；3.0–3.5 是能蹲但击球时站起来；4.0+ 多半是深球或被动球上提前起身，不要写「还不会屈膝」。
- 只动手 / 发力顺序：2.0–2.5 先练转肩迎球，不要讲伤病和髋-肩-肘-腕；4.5–5.0 现代正手转体更紧凑，2D 侧面容易误判成只动手，旁证和画面打架时少写。
- 擦玻璃：2.0–2.5 先建立由低向高，少堆术语；3.0–3.5 可以用「拍凳子」；4.0+ 写成拍面横扫、出球发飘，不要写入门口令。

【写作纪律】
- 2.0–2.5：只抓 1 件最影响能打上球的事，禁用「动力链」「加载」「肩髋分离」。
- 3.0–3.5：最多抓 2 件事，用口令，少术语。
- 4.0–4.5：点出情境（深球、追身、还原），不要写入门教条。
- 5.0：按能打球的人说话，禁止「先学会」「还不会」「坐凳练习」。
- 不要改球员申报的等级，也不要另估一个 NTRP。
- improvements 和 drills 的难度必须配得上这个等级：2.0 用自抛/对墙/标志物，5.0 用活球、深度变化和还原。"""


